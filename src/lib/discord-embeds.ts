/**
 * Standard Discord Embed Formats for Cerbis Application & Relay
 * Distinguishes automated receipts from human responses.
 */

export interface CommissionBriefData {
  name: string;
  scope: string;
  game?: string;
  message: string;
  discordId?: string;
  email?: string;
}

export const DISCORD_COLORS = {
  AUTOMATED: 0x5865f2, // Discord Blurple
  HUMAN: 0x30d158, // Verified Green
  AI_ASSISTANT: 0xa855f7, // Accent Purple
  ACCENT: 0xff4a1c, // Cerbis Brand Orange
} as const;

/**
 * Automated First Response Embed
 * Sent immediately to the client when a message or brief is received.
 */
export function buildAutomatedFirstResponseEmbed(userName?: string, scope?: string) {
  const greeting = userName ? `Hey ${userName}.` : "Hey.";

  return {
    title: "🤖 [AUTOMATED] Brief Logged",
    color: DISCORD_COLORS.AUTOMATED,
    description: `${greeting} Your message is logged in my queue. I check incoming briefs between Studio sessions.`,
    fields: [
      {
        name: "Type",
        value: "`Automated receipt`",
        inline: true,
      },
      {
        name: "Typical reply",
        value: "Same day",
        inline: true,
      },
      ...(scope
        ? [
            {
              name: "Scope",
              value: `\`${scope}\``,
              inline: true,
            },
          ]
        : []),
      {
        name: "Standard handoff",
        value: "• Figma source files\n• Studio `.rbxm` models (scaled for phone and desktop)\n• Commented Luau scripts",
        inline: false,
      },
      {
        name: "Next",
        value: "I review the game link and screens personally before quoting. My reply will appear directly in this thread with a green badge.",
        inline: false,
      },
    ],
    footer: {
      text: "Cerbis • cerbis.xyz",
    },
    timestamp: new Date().toISOString(),
  };
}

/**
 * Verified Human Response Embed
 * Sent to the client whenever Cerbis manually responds from Studio.
 */
export function buildHumanResponseEmbed(message: string, authorName = "Cerbis") {
  return {
    title: "🟢 [HUMAN] Cerbis",
    color: DISCORD_COLORS.HUMAN,
    description: message,
    fields: [
      {
        name: "Sender",
        value: authorName,
        inline: true,
      },
      {
        name: "Verification",
        value: "`Human verified`",
        inline: true,
      },
    ],
    footer: {
      text: "Direct reply from Studio • cerbis.xyz",
    },
    timestamp: new Date().toISOString(),
  };
}

/**
 * Automated AI Response Embed
 * Used when an AI assistant answers queries or preliminary intake questions.
 */
export function buildAiResponseEmbed(aiAnswer: string) {
  return {
    title: "🟣 [AUTOMATED AI] Cerbis Assistant",
    color: DISCORD_COLORS.AI_ASSISTANT,
    description: aiAnswer,
    fields: [
      {
        name: "Type",
        value: "`Automated answer`",
        inline: true,
      },
      {
        name: "Note",
        value: "Generated by bot. Cerbis confirms all final quotes and deadlines.",
        inline: true,
      },
    ],
    footer: {
      text: "cerbis.xyz",
    },
    timestamp: new Date().toISOString(),
  };
}

/**
 * Commission Brief Embed for Cerbis's Admin Inbox
 * Posted into Cerbis's private Discord channel when a client initiates a request.
 */
export function buildAdminBriefEmbed(data: CommissionBriefData) {
  return {
    title: `🎨 Brief: ${data.scope}`,
    color: DISCORD_COLORS.ACCENT,
    fields: [
      { name: "Client", value: data.name || "Anonymous", inline: true },
      { name: "Scope", value: data.scope, inline: true },
      ...(data.discordId
        ? [{ name: "Discord", value: `<@${data.discordId}> (\`${data.discordId}\`)`, inline: true }]
        : []),
      { name: "Game", value: data.game || "None provided", inline: false },
      {
        name: "Details",
        value: data.message.length > 1000 ? `${data.message.slice(0, 1000)}...` : data.message,
        inline: false,
      },
    ],
    footer: {
      text: "Reply with !reply <client_id> <message>",
    },
    timestamp: new Date().toISOString(),
  };
}
